def cut(text, begin, end, what, inclusive):
    if text.count(begin) != 1 or text.count(end) != 1:
        print("anchor for %s is not unique (%d / %d)"
              % (what, text.count(begin), text.count(end)))
        sys.exit(2)
    i, j = text.index(begin), text.index(end)
    if j < i:
        print("anchor for %s is out of order" % what)
        sys.exit(2)
    return text[i:j + len(end)] if inclusive else text[i:j]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    ap = argparse.ArgumentParser()
    ap.add_argument("--vk", default=os.path.join(root, "source", "hooks", "vk.c"))
    ap.add_argument("--keep", action="store_true", help="keep the generated harness")
    args = ap.parse_args()

    src = open(args.vk, encoding="utf-8").read()
    frame = cut(src, FRAME_BEGIN, FRAME_END, "per-frame block", False)
    report = cut(src, REPORT_BEGIN, REPORT_END, "report block", True)
    observe = cut(src, OBSERVE_BEGIN, OBSERVE_END, "observe block", True)

    out = (TEMPLATE.replace("@@FRAME@@", frame)
           .replace("@@OBSERVE@@", observe)
           .replace("@@REPORT@@", report))
    for marker, rel, start, end in HDR_TYPES:
        text = open(os.path.join(root, rel), encoding="utf-8").read()
        out = out.replace(marker, cut(text, start, end, rel, True))
    if "@@" in out:
        print("unsubstituted placeholder left in the harness")
        return 2

    tmp = tempfile.mkdtemp(prefix="vkhitch")
    c = os.path.join(tmp, "hitch_test.c")
    open(c, "w", encoding="utf-8").write(out)
    exe = os.path.join(tmp, "hitch_test")
    cmd = ["gcc", "-std=c11", "-Wall", "-Wextra", "-Wformat=2", "-Werror",
           "-o", exe, c]
    print(" ".join(cmd))
    build = subprocess.run(cmd, capture_output=True, text=True)
    if build.returncode != 0:
        print(build.stdout)
        print(build.stderr)
        return 1
    if build.stderr.strip():
        print("compiler warnings are treated as failures:")
        print(build.stderr)
        return 1
    run = subprocess.run([exe], capture_output=True, text=True)
    print(run.stdout.strip())
    if run.stderr.strip():
        print(run.stderr.strip())
    if not args.keep:
        subprocess.run(["rm", "-rf", tmp])
    else:
        print("kept in " + tmp)
    return run.returncode


if __name__ == "__main__":
    sys.exit(main())
