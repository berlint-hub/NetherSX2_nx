#!/usr/bin/env python3
"""Compile and run the per-frame hitch attribution from source/hooks/vk.c on the host.

Why this exists separately from check_vk_gpu_probe.py: every other counter in the
diagnostic log is a per-window total, and a window is 300 frames / ~6 s. A single
long frame is invisible in that -- the worst frame of the GT3 run measured on
build e0e44b4 was 82.4 ms (1% low 22.65 fps) inside a window that reported
EE 68% / GS 58% / pipelines 3.1 ms total / fence 8.1 ms total / 13046 copies.
82.4 ms is 1.4% of the window, so no percentage in it could have shown the hitch
even if that frame had been fully CPU-bound on one thread. The per-frame code
differences the same counters between two presents, so the longest frame of each
window can be reported with its own breakdown.

That bookkeeping is easy to get subtly wrong in three ways, and all three are
silent on hardware: a delta taken against a stale baseline (so the numbers are
cumulative and merely look plausible), the end-of-window reset not following the
counters it mirrors (so the next window's first delta wraps around 2^64), and the
absolute io/cpu baselines not advancing on calm frames (so a hitch gets
differenced against the previous hitch instead of the previous frame). The cases
below are those three, plus threshold behaviour, the "role not registered" path,
and a fourth thing the per-frame code cannot show on its own: perf_note_frame() is
never called for the very first present, so the two absolute baselines have to be
seeded there or the first measured frame gets credited with every byte read and
every CPU tick since boot -- and the first frames of a boot are exactly the ones
long enough to be reported as a hitch. Cases 7 and 8 therefore drive
perf_observe_present() itself (extracted verbatim too, with a fake clock) instead
of perf_note_frame(), covering the real call path, the seeding, and the
300-present window rollover.

Mutation history: removing the prev_barrier update, removing the hitch_have reset,
flipping the "longest frame" comparison, moving the threshold from 40 ms to
400 ms, and removing the first-present seeding are each caught by at least one
case.

The code under test is extracted from vk.c VERBATIM (never retyped), and the two
types it borrows from other modules are extracted from their headers verbatim, so
neither can drift past this harness. Compiled with -Wall -Wextra -Wformat=2
-Werror; unlike the GPU probe harness it needs no Vulkan headers, no devkitPro
and no GPU.

Exit status is 0 only when it compiled without warnings AND every case passed.
"""

