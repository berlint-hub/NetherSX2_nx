#!/usr/bin/env python3
"""Compile and run the file-I/O timing (libc_shim.c) and the per-frame CPU
sampling (pthr.c) on the host, both extracted VERBATIM from the sources.

These two feed one diagnostic line: the per-frame hitch report in vk.c can only
say where a long frame went if "blocked in a file read" and "CPU time of EE/GS/
MTVU during that one frame" are themselves right. Two mistakes here are silent on
hardware and would send the diagnosis the wrong way, so each has a case below:

  * counting the synthetic-descriptor branch of __read_chk_fake as I/O. That
    branch is a memcpy out of a prebuilt buffer; timing it as SD-card access
    would invent precisely the stall this counter exists to detect.
  * the tick-to-millisecond conversion. svcGetInfo(ThreadTickCount) counts at
    19.2 MHz, so armTicksToNs()/1e6 is the ms figure. A wrong divisor prints a
    plausible-looking number that is off by 1000x and would convict or exonerate
    the wrong thread.

Also checked: read() and fread() return values pass through untouched, fread
bytes are ret*size and not ret*n, a failed read counts the call but no bytes, an
unregistered or dead role prints "-" instead of a stale delta, and sampling does
NOT consume the baselines pthr_cpu_time_report() needs for its per-window
percentages -- both must be usable in the same window without disturbing each
other, which is the whole reason the sample API exists separately.

Only the diagnostic build is exercised here: with NETHERSX2_VK_DIAGNOSTIC
undefined both functions reduce to the plain forward they were before (the #else
branches are the untouched originals and CI compiles them, and the diag-only
gating itself is asserted in the workflow).

Compiled with -Wall -Wextra -Wformat=2 -Werror. No devkitPro, no GPU, no Switch:
the libnx surface used here (svcGetInfo, armTicksToNs, mutexes) is faked, and
fread is redirected to a fake because the host libc owns that name.

Exit status is 0 only when it compiled without warnings AND every case passed.
"""

import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# marker -> (file, first line of the block, last line of the block)
BLOCKS = (
    ("@@FILEIOT@@", "source/libc_shim.h",
     "typedef struct {\n  unsigned long long calls;", "} FileIoStats;"),
    ("@@ROLES@@", "source/pthr.h",
     "#define PTHR_CPU_ROLES 3", "#define PTHR_CPU_ROLES 3"),
    ("@@CPUT@@", "source/pthr.h",
     "typedef struct {\n  uint64_t ticks[PTHR_CPU_ROLES];", "} CpuTimeSample;"),
    ("@@SYNFILE@@", "source/libc_shim.c",
     "#define SYNFILE_FD_BASE", "} SynFile;"),
    ("@@FILEIOCTR@@", "source/libc_shim.c",
     "#ifdef NETHERSX2_VK_DIAGNOSTIC\n/* Updated from several threads",
     "void fileio_stats_snapshot(FileIoStats *out) {\n"
     "  out->calls = __atomic_load_n(&g_io_calls, __ATOMIC_RELAXED);\n"
     "  out->bytes = __atomic_load_n(&g_io_bytes, __ATOMIC_RELAXED);\n"
     "  out->ns    = __atomic_load_n(&g_io_ns, __ATOMIC_RELAXED);\n}\n#endif"),
    ("@@READCHK@@", "source/libc_shim.c",
     "long __read_chk_fake(int fd, void *buf, size_t count, size_t buf_size) {",
     "#else\n  return read(fd, buf, count);\n#endif\n}"),
    ("@@FREADF@@", "source/libc_shim.c",
     "size_t fread_fake(void *ptr, size_t size, size_t n, FILE *f) {",
     "#else\n  return fread(ptr, size, n, f);\n#endif\n}"),
    ("@@SLOTS@@", "source/pthr.c",
     "typedef struct {\n  const char *label;", "static Mutex cpu_time_lock;"),
    ("@@TICKS@@", "source/pthr.c",
     "static Result cpu_time_ticks(Handle h, u64 *ticks) {",
     "  return svcGetInfo(ticks, id, h, TickCountInfo_Total);\n}"),
    ("@@SAMPLE@@", "source/pthr.c",
     "#ifdef NETHERSX2_VK_DIAGNOSTIC\nvoid pthr_cpu_time_sample(CpuTimeSample *out) {",
     "  if (any)\n"
     "    n += snprintf(buf + n, n < (int)len ? len - (size_t)n : 0, \" ms\");\n"
     "  return any;\n}\n#endif"),
)

TEMPLATE = r"""
/* GENERATED by tools/check_fileio_cpu_sample.py -- do not edit. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stddef.h>
#include <time.h>
#include <sys/types.h>

@@ROLES@@
@@FILEIOT@@
@@CPUT@@

/* ---- libnx / newlib stand-ins ---- */
typedef uint64_t u64; typedef uint32_t u32; typedef uint32_t Result; typedef uint32_t Handle;
typedef int Mutex;
#define INVALID_HANDLE 0xFFFFFFFFu
#define R_FAILED(r) ((r)!=0)
static void mutexLock(Mutex *m){(void)m;} static void mutexUnlock(Mutex *m){(void)m;}
static u64 armTicksToNs(u64 t){ return (t*625u)/12u; }
#define InfoType_ThreadTickCount 25u
#define InfoType_ThreadTickCountDeprecated 0xF0000002u
#define TickCountInfo_Total UINT64_MAX
static u32 g_hosver = 13;
static int hosversionAtLeast(u32 a,u32 b,u32 c){(void)b;(void)c;return g_hosver>=a;}

/* fake kernel: per-handle tick counters, and a way to make a handle answer with
 * an error so the "thread went away" path is exercised */
static u64  fake_ticks[8];
static int  fake_dead[8];
static Result svcGetInfo(u64 *out, u32 id, Handle h, u64 sub){
  (void)id;(void)sub;
  if (h>=8 || fake_dead[h]) return 1;
  *out = fake_ticks[h]; return 0;
}
static Handle threadGetCurHandle(void){ return 0; }

/* fake filesystem */
static char   fake_content[1<<16];
static ssize_t fake_read_ret = 4096;
static size_t  fake_fread_ret = 3;
static int     fake_read_calls, fake_fread_calls;
static ssize_t read(int fd, void *buf, size_t n){ (void)fd;(void)n; ++fake_read_calls; memcpy(buf,fake_content,16); return fake_read_ret; }
#define fread fake_fread
static size_t fake_fread(void *p, size_t sz, size_t nn, FILE *f){ (void)p;(void)sz;(void)nn;(void)f; ++fake_fread_calls; return fake_fread_ret; }

/* ---- verbatim sources ---- */

static int is_fake_file(const FILE *f){ return f==(const FILE*)0x1; }
@@SYNFILE@@
static Mutex g_synfile_lock;
static SynFile g_syn;
static SynFile *synfile_get(int fd){ return fd==SYNFILE_FD_BASE ? &g_syn : NULL; }

@@FILEIOCTR@@
@@READCHK@@
@@FREADF@@

@@SLOTS@@
@@TICKS@@
@@SAMPLE@@

/* ---- tests ---- */
static int fails;
static void ck(int c,const char*w){ if(!c){ printf("  FAIL %s\n",w); ++fails; } }
int main(void){
  /* extracted verbatim together with the window reporter, which this harness
   * does not exercise; keep -Wunused quiet without touching the source text */
  (void)cpu_time_last_wall; (void)threadGetCurHandle;
  printf("== fileio: reads are timed and counted ==\n");
  char buf[64]; FileIoStats a,b;
  fileio_stats_snapshot(&a);
  long r = __read_chk_fake(7, buf, 4096, sizeof buf);
  fileio_stats_snapshot(&b);
  ck(r==4096,"read() return value preserved");
  ck(b.calls-a.calls==1,"one call counted");
  ck(b.bytes-a.bytes==4096,"bytes = what read returned");
  ck(b.ns>=a.ns,"time accumulated (monotonic clock)");
  ck(fake_read_calls==1,"reached the real read exactly once");

  printf("== fileio: the synthetic-descriptor branch is a memcpy, not I/O ==\n");
  g_syn.used=1; g_syn.content="0123456789"; g_syn.len=10; g_syn.offset=0;
  fileio_stats_snapshot(&a);
  r = __read_chk_fake(SYNFILE_FD_BASE, buf, 4, sizeof buf);
  fileio_stats_snapshot(&b);
  ck(r==4,"synthetic read returns the count it copied");
  ck(!memcmp(buf,"0123",4),"synthetic read copied the right bytes");
  ck(g_syn.offset==4,"synthetic offset advanced");
  ck(b.calls-a.calls==0 && b.ns-a.ns==0,"synthetic read NOT counted as I/O");
  ck(fake_read_calls==1,"and it did not reach the filesystem");

  printf("== fileio: a failed read counts the call but no bytes ==\n");
  g_syn.used=0; fake_read_ret=-1;
  fileio_stats_snapshot(&a);
  r = __read_chk_fake(7, buf, 4096, sizeof buf);
  fileio_stats_snapshot(&b);
  ck(r==-1,"negative result passed through");
  ck(b.calls-a.calls==1 && b.bytes-a.bytes==0,"call counted, bytes not");
  fake_read_ret=4096;

  printf("== fileio: fread bytes = returned count x element size ==\n");
  fake_fread_ret=3;
  fileio_stats_snapshot(&a);
  size_t fr = fread_fake(buf, 2048, 8, (FILE*)0x2);
  fileio_stats_snapshot(&b);
  ck(fr==3,"fread return preserved");
  ck(b.bytes-a.bytes==3*2048,"bytes = ret*size, not ret*n");
  printf("== fileio: a fake FILE* is not read at all ==\n");
  fileio_stats_snapshot(&a);
  fr = fread_fake(buf, 2048, 8, (FILE*)0x1);
  fileio_stats_snapshot(&b);
  ck(fr==0 && b.calls-a.calls==0,"fake FILE* short-circuits");

  printf("== cpu sample: three live roles ==\n");
  for (int i=0;i<3;++i){ cpu_time_slots[i].handle=(Handle)i; fake_ticks[i]=0; fake_dead[i]=0; }
  CpuTimeSample s0,s1; pthr_cpu_time_sample(&s0);
  fake_ticks[0]=19200*51; fake_ticks[1]=19200*25; fake_ticks[2]=19200*12;  /* 19.2 MHz */
  pthr_cpu_time_sample(&s1);
  char out[96];
  ck(pthr_cpu_time_ms(&s0,&s1,out,sizeof out)==1,"delta usable");
  ck(!strcmp(out,"EE 51.0 GS 25.0 MTVU 12.0 ms"),"ticks->ms at 19.2 MHz");
  printf("   [%s]\n",out);

  printf("== cpu sample: baselines are untouched, so the window report still works ==\n");
  u64 keep0=cpu_time_slots[0].last_ticks, keep1=cpu_time_slots[1].last_ticks;
  pthr_cpu_time_sample(&s1);
  ck(cpu_time_slots[0].last_ticks==keep0 && cpu_time_slots[1].last_ticks==keep1,
     "sampling does not consume the rate baselines");

  printf("== cpu sample: unregistered and dead handles ==\n");
  cpu_time_slots[1].handle=INVALID_HANDLE; fake_dead[2]=1;
  pthr_cpu_time_sample(&s0); fake_ticks[0]+=19200*7; pthr_cpu_time_sample(&s1);
  ck(pthr_cpu_time_ms(&s0,&s1,out,sizeof out)==1,"still usable for the live role");
  ck(!strcmp(out,"EE 7.0 GS - MTVU - ms"),"missing roles print '-'");
  printf("   [%s]\n",out);
  ck(pthr_cpu_time_ms(&s1,&s0,out,sizeof out)==0,"backwards delta refuses");
  ck(pthr_cpu_time_ms(NULL,&s1,out,sizeof out)==0,"NULL from refuses");
  if(fails){ printf("FUNCTIONAL FAIL (%d)\n",fails); return 1; }
  printf("FUNCTIONAL OK\n"); return 0;
}
"""


def cut(text, begin, end, what):
    if text.count(begin) != 1 or text.count(end) != 1:
        print("anchor for %s is not unique (%d / %d)"
              % (what, text.count(begin), text.count(end)))
        sys.exit(2)
    i, j = text.index(begin), text.index(end)
    if j < i:
        print("anchor for %s is out of order" % what)
        sys.exit(2)
    return text[i:j + len(end)]


def main():
    cache = {}
    out = TEMPLATE
    for marker, rel, start, end in BLOCKS:
        if rel not in cache:
            cache[rel] = open(os.path.join(ROOT, rel), encoding="utf-8").read()
        out = out.replace(marker, cut(cache[rel], start, end, rel))
    if "@@" in out:
        print("unsubstituted placeholder left in the harness")
        return 2

    tmp = tempfile.mkdtemp(prefix="fileio")
    c = os.path.join(tmp, "io_test.c")
    open(c, "w", encoding="utf-8").write(out)
    exe = os.path.join(tmp, "io_test")
    cmd = ["gcc", "-std=c11", "-D_POSIX_C_SOURCE=200809L",
           "-DNETHERSX2_VK_DIAGNOSTIC",
           "-Wall", "-Wextra", "-Wformat=2", "-Werror", "-o", exe, c]
    print(" ".join(cmd))
    build = subprocess.run(cmd, capture_output=True, text=True)
    if build.returncode != 0:
        print(build.stdout)
        print(build.stderr)
        return 1
    if build.stderr.strip():
        print("compiler warnings are treated as failures:")
        print(build.stderr)
        return 1
    run = subprocess.run([exe], capture_output=True, text=True)
    print(run.stdout.strip())
    if run.stderr.strip():
        print(run.stderr.strip())
    if "--keep" in sys.argv:
        print("kept in " + tmp)
    else:
        subprocess.run(["rm", "-rf", tmp])
    return run.returncode


if __name__ == "__main__":
    sys.exit(main())
